-- 0004 (PostgreSQL): fundação V3 para pacientes e biblioteca operacional.
--
-- Este arquivo não cria buckets nem manipula o schema interno storage. O bucket
-- privado será provisionado pela API/Dashboard do Supabase depois da autenticação
-- operacional e da revisão das políticas de acesso.

CREATE TABLE agende_bem.patients (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    display_name text NOT NULL CHECK (char_length(display_name) BETWEEN 2 AND 80),
    status      text NOT NULL DEFAULT 'ativo' CHECK (status IN ('ativo', 'inativo')),
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX patients_display_name_ci_key
    ON agende_bem.patients (lower(display_name));
CREATE INDEX patients_status_idx ON agende_bem.patients (status);

-- Conteúdo fica no Supabase Storage; esta tabela contém apenas metadados.
CREATE TABLE agende_bem.file_assets (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    original_name      text NOT NULL CHECK (char_length(original_name) BETWEEN 1 AND 255),
    display_name       text NOT NULL CHECK (char_length(display_name) BETWEEN 1 AND 120),
    file_extension     text NOT NULL CHECK (file_extension ~ '^[a-z0-9]{1,10}$'),
    mime_type          text NOT NULL CHECK (mime_type IN ('text/csv', 'application/pdf')),
    byte_size          bigint NOT NULL CHECK (byte_size > 0 AND byte_size <= 5242880),
    storage_bucket     text NOT NULL CHECK (storage_bucket ~ '^[a-z0-9][a-z0-9-]{1,62}$'),
    storage_object_key text NOT NULL CHECK (
        storage_object_key !~ '^/'
        AND position('..' IN storage_object_key) = 0
        AND position(E'\\' IN storage_object_key) = 0
    ),
    sha256             text NOT NULL CHECK (sha256 ~ '^[0-9a-f]{64}$'),
    category           text NOT NULL CHECK (category IN ('operacional', 'modelo')),
    status             text NOT NULL DEFAULT 'ativo' CHECK (status IN ('ativo', 'arquivado')),
    created_at         timestamptz NOT NULL DEFAULT now(),
    updated_at         timestamptz NOT NULL DEFAULT now(),
    UNIQUE (storage_bucket, storage_object_key)
);
CREATE INDEX file_assets_category_status_idx
    ON agende_bem.file_assets (category, status, created_at DESC);

CREATE TABLE agende_bem.file_templates (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title            text NOT NULL CHECK (char_length(title) BETWEEN 2 AND 120),
    description      text NOT NULL DEFAULT '' CHECK (char_length(description) <= 500),
    category         text NOT NULL CHECK (category IN ('agenda', 'lista_espera', 'profissionais', 'guia', 'relatorio')),
    template_type    text NOT NULL CHECK (template_type IN ('csv', 'pdf')),
    current_asset_id bigint NOT NULL REFERENCES agende_bem.file_assets (id),
    current_version  integer NOT NULL DEFAULT 1 CHECK (current_version > 0),
    status           text NOT NULL DEFAULT 'ativo' CHECK (status IN ('ativo', 'arquivado')),
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),
    UNIQUE (title)
);

CREATE TABLE agende_bem.file_template_versions (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    template_id      bigint NOT NULL REFERENCES agende_bem.file_templates (id),
    version_number   integer NOT NULL CHECK (version_number > 0),
    asset_id         bigint NOT NULL REFERENCES agende_bem.file_assets (id),
    change_summary   text NOT NULL DEFAULT '' CHECK (char_length(change_summary) <= 500),
    created_at       timestamptz NOT NULL DEFAULT now(),
    UNIQUE (template_id, version_number)
);
CREATE INDEX file_template_versions_template_idx
    ON agende_bem.file_template_versions (template_id, version_number DESC);

CREATE FUNCTION agende_bem.set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog
AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END
$$;
REVOKE ALL ON FUNCTION agende_bem.set_updated_at() FROM PUBLIC;

CREATE TRIGGER patients_set_updated_at
    BEFORE UPDATE ON agende_bem.patients
    FOR EACH ROW EXECUTE FUNCTION agende_bem.set_updated_at();
CREATE TRIGGER file_assets_set_updated_at
    BEFORE UPDATE ON agende_bem.file_assets
    FOR EACH ROW EXECUTE FUNCTION agende_bem.set_updated_at();
CREATE TRIGGER file_templates_set_updated_at
    BEFORE UPDATE ON agende_bem.file_templates
    FOR EACH ROW EXECUTE FUNCTION agende_bem.set_updated_at();

GRANT SELECT, INSERT, UPDATE, DELETE ON
    agende_bem.patients,
    agende_bem.file_assets,
    agende_bem.file_templates,
    agende_bem.file_template_versions
TO agende_bem_app;
GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA agende_bem TO agende_bem_app;

ALTER TABLE agende_bem.patients ENABLE ROW LEVEL SECURITY;
ALTER TABLE agende_bem.file_assets ENABLE ROW LEVEL SECURITY;
ALTER TABLE agende_bem.file_templates ENABLE ROW LEVEL SECURITY;
ALTER TABLE agende_bem.file_template_versions ENABLE ROW LEVEL SECURITY;

CREATE POLICY agende_bem_app_all ON agende_bem.patients
    FOR ALL TO agende_bem_app USING (true) WITH CHECK (true);
CREATE POLICY agende_bem_app_all ON agende_bem.file_assets
    FOR ALL TO agende_bem_app USING (true) WITH CHECK (true);
CREATE POLICY agende_bem_app_all ON agende_bem.file_templates
    FOR ALL TO agende_bem_app USING (true) WITH CHECK (true);
CREATE POLICY agende_bem_app_all ON agende_bem.file_template_versions
    FOR ALL TO agende_bem_app USING (true) WITH CHECK (true);
