-- 0001 (PostgreSQL): esquema privado do Agende Bem.
-- O esquema "agende_bem" NÃO deve ser adicionado aos "Exposed schemas" da API do Supabase.

CREATE SCHEMA IF NOT EXISTS agende_bem;

-- btree_gist permite a restrição de exclusão que impede consultas sobrepostas.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_namespace WHERE nspname = 'extensions') THEN
        CREATE EXTENSION IF NOT EXISTS btree_gist WITH SCHEMA extensions;  -- padrão Supabase
    ELSE
        CREATE EXTENSION IF NOT EXISTS btree_gist;
    END IF;
END
$$;

CREATE TABLE agende_bem.settings (
    key   text PRIMARY KEY,
    value text NOT NULL
);

CREATE TABLE agende_bem.professionals (
    id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      text     NOT NULL UNIQUE CHECK (char_length(name) BETWEEN 2 AND 80),
    specialty text     NOT NULL DEFAULT '' CHECK (char_length(specialty) <= 60),
    day_start text     NOT NULL DEFAULT '08:00' CHECK (day_start ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
    day_end   text     NOT NULL DEFAULT '18:00' CHECK (day_end ~ '^([01][0-9]|2[0-4]):[0-5][0-9]$'),
    active    smallint NOT NULL DEFAULT 1 CHECK (active IN (0, 1))
);

CREATE TABLE agende_bem.waiting_list (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_name     text    NOT NULL CHECK (char_length(patient_name) BETWEEN 2 AND 80),
    professional_ids text    NOT NULL CHECK (professional_ids ~ '^[0-9]+(,[0-9]+)*$'),
    duration_min     integer NOT NULL CHECK (duration_min > 0),
    available_from   text    NOT NULL CHECK (available_from ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
    available_until  text    NOT NULL CHECK (available_until ~ '^([01][0-9]|2[0-4]):[0-5][0-9]$'),
    requested_on     date    NOT NULL,
    status           text    NOT NULL DEFAULT 'ativo'
                     CHECK (status IN ('ativo', 'encaixado', 'removido')),
    notes            text    NOT NULL DEFAULT '' CHECK (char_length(notes) <= 200),
    created_at       timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX waiting_list_status_idx ON agende_bem.waiting_list (status);

CREATE TABLE agende_bem.appointments (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_name    text    NOT NULL CHECK (char_length(patient_name) BETWEEN 2 AND 80),
    professional_id bigint  NOT NULL REFERENCES agende_bem.professionals (id),
    day             date    NOT NULL,
    start_time      text    NOT NULL CHECK (start_time ~ '^([01][0-9]|2[0-3]):[0-5][0-9]$'),
    duration_min    integer NOT NULL CHECK (duration_min > 0),
    start_min       integer GENERATED ALWAYS AS (
                        split_part(start_time, ':', 1)::integer * 60
                        + split_part(start_time, ':', 2)::integer
                    ) STORED,
    status          text    NOT NULL DEFAULT 'confirmado'
                    CHECK (status IN ('confirmado', 'cancelado')),
    origin          text    NOT NULL DEFAULT 'agenda'
                    CHECK (origin IN ('agenda', 'encaixe')),
    replaces_id     bigint  REFERENCES agende_bem.appointments (id),
    waiting_id      bigint  REFERENCES agende_bem.waiting_list (id),
    created_at      timestamptz NOT NULL DEFAULT now(),
    cancelled_at    timestamptz,
    -- Garantia no banco: duas consultas confirmadas do mesmo profissional não se sobrepõem.
    CONSTRAINT appointments_no_overlap EXCLUDE USING gist (
        professional_id WITH =,
        day WITH =,
        int4range(start_min, start_min + duration_min) WITH &&
    ) WHERE (status = 'confirmado')
);
CREATE INDEX appointments_day_idx ON agende_bem.appointments (day, professional_id);

CREATE TABLE agende_bem.audit_events (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at timestamptz NOT NULL DEFAULT now(),
    event_type text   NOT NULL,
    entity     text   NOT NULL,
    entity_id  bigint,
    details    text   NOT NULL DEFAULT ''
);
